package cli

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"

	"github.com/f-klement/errata/internal/config"
)

// referenceHeader is the start of docs/cli.md: its first line says it is
// generated, and by which target.
const referenceHeader = "This file is generated by `make cli-doc`. Do not edit it.\n" +
	"Edit the help in internal/cli/help.go and run `make cli-doc`.\n"

// documented is errata and every command below it that its help lists, in
// the order the help lists them: the available commands, and help, which
// cobra lists though it does not count it as available. Hidden commands,
// such as cobra's __complete, are left out.
func documented(root *cobra.Command) []*cobra.Command {
	cmds := []*cobra.Command{root}
	for _, c := range root.Commands() {
		if c.IsAvailableCommand() || c.Name() == "help" {
			cmds = append(cmds, documented(c)...)
		}
	}
	return cmds
}

// argsOf is the arguments that name c below the root: errata completion
// bash is [completion bash].
func argsOf(c *cobra.Command) []string {
	return strings.Fields(c.CommandPath())[1:]
}

// anchorOf is the anchor GitHub gives the heading of c's section.
func anchorOf(c *cobra.Command) string {
	return strings.ReplaceAll(c.CommandPath(), " ", "-")
}

// Reference is docs/cli.md: the help of errata and of each command below
// it, each as errata prints it for --help, under a heading of its own, after
// a table of contents. make cli-doc writes it, and the tag pipeline refuses
// a release whose docs/cli.md differs from it. The help leaves out the line
// that points at docs/cli.md, so the file does not depend on the version
// that writes it.
func Reference() ([]byte, error) {
	cmds := documented(newRoot(config.Load, io.Discard, io.Discard))
	var b bytes.Buffer
	b.WriteString(referenceHeader + "\n# errata command line\n\n")
	b.WriteString("The help of errata and of each of its commands, as `errata --help` and\n" +
		"`errata <command> --help` print it.\n\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "- [%s](#%s)\n", c.CommandPath(), anchorOf(c))
	}
	for _, c := range cmds {
		help, err := helpText(argsOf(c))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\n## %s\n\n```text\n%s```\n", c.CommandPath(), help)
	}
	return b.Bytes(), nil
}

// helpText is what `errata <args> --help` prints, without the line naming
// docs/cli.md: the root command carries no reference annotation here.
func helpText(args []string) (string, error) {
	var out, errs bytes.Buffer
	root := newRoot(config.Load, &out, &errs)
	root.SetArgs(append(append([]string{}, args...), "--help"))
	if err := root.ExecuteContext(context.Background()); err != nil {
		return "", fmt.Errorf("help of %q: %w", args, err)
	}
	if errs.Len() > 0 {
		return "", fmt.Errorf("help of %q wrote to stderr: %s", args, errs.String())
	}
	return out.String(), nil
}
